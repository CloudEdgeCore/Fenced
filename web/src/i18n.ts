export type StringKey = keyof typeof EN;
export type ColumnKey = keyof typeof EN_COLUMNS;

export function translator(language: Language): (key: StringKey) => string {
  const table: Record<StringKey, string> = language === 'zh' ? ZH : EN;
  return (key) => table[key];
}

export function column(language: Language, key: ColumnKey): string {
  const table: Record<ColumnKey, string> = language === 'zh' ? ZH_COLUMNS : EN_COLUMNS;
  return table[key];
}
